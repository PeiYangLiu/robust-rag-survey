#!/usr/bin/env python3
"""Macros for the revision experiments (reviewer W1--W5, W7, W8).

Every number the revised manuscript prints about the redesigned disclosure
benchmark, the constructed provenance reference and the screen-recall sample is
emitted here from the artifact that produced it, so the prose cannot drift from
the data.  Writes ``tables/revision2_macros.tex``.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SUP = REPO / "manuscript" / "supplement"
TAB = REPO / "manuscript" / "tables"
MISSING = r"\textbf{??}"


def load(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def macro(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def num(x, nd=2):
    return MISSING if x is None else f"{float(x):.{nd}f}"


def pct(x, nd=0):
    return MISSING if x is None else f"{float(x) * 100:.{nd}f}"


def ci(pair, nd=2):
    if not pair:
        return MISSING
    return f"[{float(pair[0]):.{nd}f}, {float(pair[1]):.{nd}f}]"


def main() -> int:
    lines = ["% Generated by scripts/build_revision2_macros.py -- do not edit by hand."]

    # ---------------- redesigned disclosure benchmark ----------------
    inst = load(SUP / "comparability_instrument_v2_results.json") or {}
    bench = load(SUP / "comparability_instrument_benchmark_v2_summary.json") or {}
    bd = inst.get("by_disclosure", {})
    bp = inst.get("by_presentation", {})
    pooled = inst.get("pooled_non_degenerate", {})

    def cell(block, key, est="Five coordinates (rule)"):
        if not block:
            return None
        if key == "coord":
            return block.get("coordinate_recovery_mean_threatening")
        if key == "kappa":
            return block.get("verdict_fleiss_kappa")
        if key == "base":
            return block.get("constant_baseline")
        if key == "n":
            return block.get("n_items")
        return (block.get("estimators", {}).get(est) or {}).get("pooled_accuracy")

    full, bal, force = bd.get("full"), bd.get("partial_balanced"), bd.get("partial_forcing")
    canon, natu = bp.get("canonical"), bp.get("naturalistic")
    jv = "Judge verdict, five-coordinate prompt"

    lines += [
        macro("InsTwoItems", str(bench.get("n_items", MISSING))),
        macro("InsTwoSpecs", str(bench.get("n_specifications", MISSING))),
        macro("InsTwoScored", str(inst.get("n_items_scored", MISSING))),
        macro("InsTwoJudges", str(len(inst.get("judges", [])) or MISSING)),
        macro("InsTwoBase", num(cell(pooled, "base"), 3)),
        macro("InsTwoRule", num(cell(pooled, "rule"), 3)),
        # full disclosure
        macro("InsFullN", str(cell(full, "n") or MISSING)),
        macro("InsFullBase", num(cell(full, "base"), 2)),
        macro("InsFullCoord", num(cell(full, "coord"), 2)),
        macro("InsFullRule", num(cell(full, "rule"), 2)),
        macro("InsFullJudge", num(cell(full, "rule", jv), 2)),
        macro("InsFullK", num(cell(full, "kappa"), 2)),
        # withheld but not decisive
        macro("InsBalN", str(cell(bal, "n") or MISSING)),
        macro("InsBalBase", num(cell(bal, "base"), 2)),
        macro("InsBalCoord", num(cell(bal, "coord"), 2)),
        macro("InsBalRule", num(cell(bal, "rule"), 2)),
        macro("InsBalJudge", num(cell(bal, "rule", jv), 2)),
        macro("InsBalK", num(cell(bal, "kappa"), 2)),
        # withheld and decisive
        macro("InsForceN", str(cell(force, "n") or MISSING)),
        macro("InsForceBase", num(cell(force, "base"), 2)),
        macro("InsForceCoord", num(cell(force, "coord"), 2)),
        macro("InsForceRule", num(cell(force, "rule"), 2)),
        macro("InsForceJudge", num(cell(force, "rule", jv), 2)),
        macro("InsForceK", num(cell(force, "kappa"), 2)),
        macro("InsForceFive", num(cell(force, "rule"), 2)),
        macro("InsForceTwo", num(cell(force, "rule",
                                      "Two coordinates (rule, C1/C4 prompt)"), 2)),
        macro("InsForceJudgeTwo", num(cell(force, "rule",
                                           "Judge verdict, C1/C4 prompt"), 2)),
        # prose realism
        macro("InsCanonCoord", num(cell(canon, "coord"), 2)),
        macro("InsCanonRule", num(cell(canon, "rule"), 2)),
        macro("InsCanonK", num(cell(canon, "kappa"), 2)),
        macro("InsNatCoord", num(cell(natu, "coord"), 2)),
        macro("InsNatRule", num(cell(natu, "rule"), 2)),
        macro("InsNatK", num(cell(natu, "kappa"), 2)),
    ]

    fv = inst.get("five_vs_two_coordinates", {})
    best_two = fv.get("five_rule_vs_best_two_coordinate_estimator", {})
    two_rule = fv.get("five_rule_vs_two_coordinate_rule", {})
    lines += [
        macro("InsFiveAcc", num(best_two.get("accuracy_a"), 3)),
        macro("InsBestTwoAcc", num(best_two.get("accuracy_b"), 3)),
        macro("InsFiveVsTwoDiff", (f"{best_two['difference']:+.3f}"
                                  if best_two.get("difference") is not None else MISSING)),
        macro("InsFiveVsTwoP", (f"{best_two['mcnemar_p_two_sided']:.3g}"
                               if best_two.get("mcnemar_p_two_sided") is not None else MISSING)),
        macro("InsTwoRuleAcc", num(two_rule.get("accuracy_b"), 3)),
    ]
    for name, key in (("InsArmFiveRule", "Five coordinates (rule)"),
                      ("InsArmTwoRule", "Two coordinates (rule, C1/C4 prompt)"),
                      ("InsArmAblated", "Rule with C2/C5 ablated"),
                      ("InsArmJudgeFive", "Judge verdict, five-coordinate prompt"),
                      ("InsArmJudgeTwo", "Judge verdict, C1/C4 prompt"),
                      ("InsArmJudgeDirect", "Judge verdict, no coordinates")):
        v = (pooled.get("estimators", {}).get(key) or {}).get("pooled_accuracy")
        lines.append(macro(name, num(v, 3)))

    # ---------------- constructed provenance reference ----------------
    prov = load(SUP / "provenance_benchmark_results.json") or {}
    dep = prov.get("deployed", {})
    panel = (dep.get("panels") or {}).get("census_three_judge_panel", {})
    pb = load(SUP / "provenance_benchmark_summary.json") or {}
    by_cls = panel.get("by_class", {})
    lines += [
        macro("PvItems", str(pb.get("n_items", MISSING))),
        macro("PvScored", str(panel.get("n_scored", MISSING))),
        macro("PvBase", num(panel.get("constant_baseline"), 3)),
        macro("PvAcc", num(panel.get("accuracy"), 3)),
        macro("PvAccCI", ci(panel.get("ci95"))),
        macro("PvExplicit", num((panel.get("by_explicitness", {}).get("explicit") or {}).get("accuracy"), 3)),
        macro("PvImplicit", num((panel.get("by_explicitness", {}).get("implicit") or {}).get("accuracy"), 3)),
        macro("PvRecallTrans", num((by_cls.get("transported") or {}).get("recall"), 3)),
        macro("PvRecallReimpl", num((by_cls.get("reimplemented") or {}).get("recall"), 3)),
        macro("PvRecallUnclear", num((by_cls.get("unclear") or {}).get("recall"), 3)),
        macro("PvPrecTrans", num((by_cls.get("transported") or {}).get("precision"), 3)),
        macro("PvPrecReimpl", num((by_cls.get("reimplemented") or {}).get("precision"), 3)),
        macro("PvJudgesN", str(len(dep.get("judges", [])) or MISSING)),
    ]
    disp = dep.get("asserted_no_number_disposition", {})
    tot = sum(disp.values()) or 1
    lines += [
        macro("PvAssertedN", str(dep.get("n_asserted_no_number_items", MISSING))),
        macro("PvAssertedUnclearPct", pct(disp.get("unclear", 0) / tot, 0)),
    ]
    corr = (prov.get("census_composition_bias_correction") or {})
    lines += [
        macro("PvObsShare", pct(corr.get("observed_reimplemented_share"), 1)),
        macro("PvCorrShare", pct(((corr.get("corrected") or {}).get("reimplemented_share")), 1)),
    ]

    # ---------------- screen recall ----------------
    rec = load(SUP / "screen_recall_results.json") or {}
    pt = rec.get("point_estimates") or {}
    rci = rec.get("cluster_bootstrap_ci95") or {}
    lines += [
        macro("RecUniverse", f"{rec.get('n_universe_windows', 0):,}"
              if rec.get("n_universe_windows") else MISSING),
        macro("RecMissed", f"{rec.get('n_missed_windows', 0):,}"
              if rec.get("n_missed_windows") else MISSING),
        macro("RecSampled", str(rec.get("n_missed_coded", MISSING))),
        macro("RecPapers", str(rec.get("n_source_papers_in_sample", MISSING))),
        macro("RecEligMissed", num(pt.get("missed_eligible_rate"), 2)),
        macro("RecEligFrame", num(pt.get("frame_eligible_rate"), 2)),
        macro("RecTrans", num(pt.get("recall_transported"), 2)),
        macro("RecTransCI", ci(rci.get("recall_transported"))),
        macro("RecReimpl", num(pt.get("recall_reimplemented"), 2)),
        macro("RecReimplCI", ci(rci.get("recall_reimplemented"))),
        macro("RecFrameShare", pct(pt.get("frame_reimplemented_share"), 0)),
        macro("RecUniverseShare", pct(pt.get("universe_reimplemented_share"), 0)),
        macro("RecUniverseShareCI",
              (f"[{rci['universe_reimplemented_share'][0] * 100:.0f}, "
               f"{rci['universe_reimplemented_share'][1] * 100:.0f}]")
              if rci.get("universe_reimplemented_share") else MISSING),
    ]

    # ---------------- sigma_r reconciliation ----------------
    multi = load(SUP / "sigma_r_multi_anchor.json") or {}
    anchors = multi.get("anchors", {})
    cen = anchors.get("census_verdict_panel", {})
    ins = anchors.get("instrument_benchmark", {})
    lines += [
        macro("SigCensusRev", str(cen.get("n_reviewers", MISSING))),
        macro("SigCensusItems", str(cen.get("n_items", MISSING))),
        macro("SigCensusVal", num(cen.get("sigma_r"))),
        macro("SigCensusCI", ci(cen.get("bootstrap_reviewers_ci95"))),
        macro("SigInsRev", str(ins.get("n_reviewers", MISSING))),
        macro("SigInsItems", str(ins.get("n_items", MISSING))),
        macro("SigInsVal", num(ins.get("sigma_r"))),
        macro("SigInsCI", ci(ins.get("bootstrap_reviewers_ci95"))),
    ]

    # ---------------- power at the measured sigma_r ----------------
    sim = load(SUP / "retrospective_remedy_simulation.json") or {}
    ins_sigma = (anchors.get("instrument_benchmark") or {}).get("sigma_r")
    power = None
    if sim.get("rows") and ins_sigma is not None:
        cand = [r for r in sim["rows"]
                if r.get("quantity") == "power"
                and r.get("reviewer_abilities") == "resampled"
                and r.get("sources") == 80]
        if cand:
            best = min(cand, key=lambda r: abs(float(r["sigma_r"]) - float(ins_sigma)))
            power = best.get("reviewer_mean_t")
    lines += [
        macro("SimTwelvePower", pct(power, 0)),
        macro("SimReviewers", str(sim.get("reviewers", MISSING))),
    ]

    (TAB / "revision2_macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    missing = [l for l in lines if MISSING in l]
    print(f"wrote {TAB / 'revision2_macros.tex'} with {len(lines) - 1} macros")
    if missing:
        print(f"{len(missing)} macros are unresolved:")
        for m in missing:
            print("   ", m)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
