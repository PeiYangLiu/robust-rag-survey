#!/usr/bin/env python3
"""Emit the tables the third revision adds, straight from their artifacts.

Nothing here is typed by hand.  Each table is written from the JSON file that
produced it, so a table cannot disagree with the analysis that generated it.
Writes into ``tables/``.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SUP = REPO / "manuscript" / "supplement"
TAB = REPO / "manuscript" / "tables"


def load(name: str):
    path = SUP / name
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def f(x, nd=2, signed=False):
    if x is None or (isinstance(x, float) and x != x):
        return "--"
    return f"{float(x):+.{nd}f}" if signed else f"{float(x):.{nd}f}"


def i(x):
    return "--" if x is None else f"{int(x):,}"


def ci(pair, nd=2):
    if not pair or len(pair) != 2 or any(p is None or p != p for p in pair):
        return "--"
    return f"[{float(pair[0]):.{nd}f}, {float(pair[1]):.{nd}f}]"


