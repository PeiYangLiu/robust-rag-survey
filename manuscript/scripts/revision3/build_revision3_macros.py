#!/usr/bin/env python3
"""Macros for the third revision (reviewer W1--W14).

Every number the revised manuscript prints about the privileged-information
reference, the information ladder, the abstention arm, the composed rule, the
quote forensics, the disclosure counterfactual, the kappa ceilings, the recall
sensitivity and the documented sampling frame is emitted here from the artifact
that produced it.  Writes ``tables/revision3_macros.tex``.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SUP = REPO / "manuscript" / "supplement"
TAB = REPO / "manuscript" / "tables"
MISSING = r"\textbf{??}"


def load(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def dig(obj, *path, default=None):
    cur = obj
    for key in path:
        if cur is None:
            return default
        try:
            cur = cur[key]
        except (KeyError, IndexError, TypeError):
            return default
    return cur if cur is not None else default


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def num(x, nd=2):
    if x is None or (isinstance(x, float) and x != x):
        return MISSING
    return f"{float(x):.{nd}f}"


def pct(x, nd=0):
    if x is None or (isinstance(x, float) and x != x):
        return MISSING
    return f"{float(x) * 100:.{nd}f}"


def integer(x):
    if x is None:
        return MISSING
    return f"{int(x):,}"


def ci(pair, nd=2):
    if not pair or len(pair) != 2 or any(p is None or p != p for p in pair):
        return MISSING
    return f"[{float(pair[0]):.{nd}f}, {float(pair[1]):.{nd}f}]"


def signed(x, nd=2):
    if x is None or (isinstance(x, float) and x != x):
        return MISSING
    return f"{float(x):+.{nd}f}"


def main() -> int:
    priv = load(SUP / "privileged_reference_results.json")
    diag = load(SUP / "census_diagnostics.json")
    absn = load(SUP / "abstention_verdict_results.json")
    disc = load(SUP / "disclosure_counterfactual.json")
    prev = load(SUP / "coordinate_prevalence.json")
    lspace = load(SUP / "label_space_matched.json")
    recall = load(SUP / "screen_recall_sensitivity.json")
    flow = load(SUP / "screening_frame_flow.json")
    sigma = load(SUP / "sigma_r_interval_design.json")
    motiv = load(SUP / "motivating_case_verification.json")
    sample = load(SUP / "privileged_reference_sample_summary.json")

    lines = [
        "% Generated by scripts/revision3/build_revision3_macros.py -- do not edit by hand.",
    ]
    add = lines.append

    # ---------------- privileged reference and the ladder -------------------
    add(macro("PrivN", integer(dig(sample, "sample_n"))))
    add(macro("PrivPapers", integer(dig(sample, "sample_papers"))))
    add(macro("PrivBoth", integer(dig(sample, "n_cited_text_available"))))
    add(macro("PrivPopulation", integer(dig(sample, "population_n"))))

    lad_v = dig(priv, "information_ladder", "comparability", default={})
    lad_p = dig(priv, "information_ladder", "provenance", default={})
    for tag, blk in (("Vd", lad_v), ("Pv", lad_p)):
        for tier, short in (("window", "Win"), ("citing_full", "Cite"), ("both_full", "Both")):
            cell = dig(blk, tier, default={})
            add(macro(f"Lad{tag}{short}K", num(cell.get("fleiss_kappa"))))
            add(macro(f"Lad{tag}{short}Obs", num(cell.get("observed"))))
            add(macro(f"Lad{tag}{short}N", integer(cell.get("n_items"))))
            add(macro(f"Lad{tag}{short}KCI", ci(cell.get("fleiss_kappa_ci95"))))
        add(macro(f"Lad{tag}DeltaCite", signed(dig(blk, "delta_citing_minus_window", "point"))))
        add(macro(f"Lad{tag}DeltaCiteCI", ci(dig(blk, "delta_citing_minus_window", "ci95"))))
        add(macro(f"Lad{tag}DeltaBoth", signed(dig(blk, "delta_both_minus_window", "point"))))
        add(macro(f"Lad{tag}DeltaBothCI", ci(dig(blk, "delta_both_minus_window", "ci95"))))

    for pass_name, tag in (("provenance", "Pv"), ("comparability", "Vd")):
        cov = dig(priv, "reference_coverage", pass_name, default={})
        add(macro(f"Ref{tag}N", integer(cov.get("n_established"))))
        add(macro(f"Ref{tag}NoMaj", integer(cov.get("n_no_majority"))))
        add(macro(f"Ref{tag}NLooEst", integer(cov.get("n_established_loo"))))
        add(macro(f"Ref{tag}BothTier", integer(dig(cov, "tier_distribution", "both_full"))))
        sc = dig(priv, "deployed_vs_reference", f"{pass_name}__all", default={})
        add(macro(f"Dep{tag}N", integer(sc.get("n_reference_items"))))
        add(macro(f"Dep{tag}Acc", num(sc.get("accuracy"))))
        add(macro(f"Dep{tag}CI", ci(sc.get("cluster_ci95"))))
        add(macro(f"Dep{tag}Base", num(sc.get("majority_class_baseline"))))
        add(macro(f"Dep{tag}Wilson", ci(sc.get("wilson_ci95"))))
        sl = dig(priv, "deployed_vs_reference", f"{pass_name}__loo", default={})
        add(macro(f"Dep{tag}AccLoo", num(sl.get("accuracy"))))
        add(macro(f"Dep{tag}NLoo", integer(sl.get("n_reference_items"))))
    for cls, short in (("transported", "Trans"), ("reimplemented", "Reimpl"), ("unclear", "Unclear")):
        blk = dig(priv, "provenance_per_class_recall", cls, default={})
        add(macro(f"RefRecall{short}", num(blk.get("recall"))))
        add(macro(f"RefRecall{short}N", integer(blk.get("n"))))
    add(macro("RefCorrSens", num(dig(priv, "composition_bias_correction", "sensitivity_transported"))))
    add(macro("RefCorrSpec", num(dig(priv, "composition_bias_correction", "specificity_transported"))))
    add(
        macro(
            "RefCorrShare",
            pct(dig(priv, "composition_bias_correction", "corrected_frame_share_reimplemented"), 1),
        )
    )

    # ---------------- composed rule ----------------------------------------
    cr = dig(diag, "composed_rule", default={})
    add(macro("RuleFidelity", num(cr.get("pooled_judge_level_rule_fidelity"))))
    add(macro("RuleMajAgree", num(cr.get("majority_agreement_rate"))))
    add(macro("RuleSurvivesContra", pct(cr.get("share_of_survives_contradicted"), 0)))
    add(macro("RuleSurvivesContraN", integer(cr.get("n_majority_survives_contradicted_by_own_coordinates"))))
    add(macro("RuleSurvivesN", integer(cr.get("n_majority_survives"))))
    add(macro("RuleKStated", num(cr.get("fleiss_kappa_stated_verdict"))))
    add(macro("RuleKComposed", num(cr.get("fleiss_kappa_composed_verdict"))))
    add(macro("RuleKDiff", signed(cr.get("kappa_composed_minus_stated"))))
    add(macro("RuleKDiffCI", ci(cr.get("kappa_composed_minus_stated_ci95"))))

    # ---------------- accounting (W13) --------------------------------------
    fr = dig(diag, "frame", default={})
    add(macro("CensusDevCoded", integer(fr.get("n_development_pass_also_coded"))))
    add(macro("CensusCodedAll", integer(fr.get("n_coded_by_all_judges"))))

    # ---------------- quote forensics ---------------------------------------
    qf = dig(diag, "quote_forensics", default={})
    cls = dig(qf, "classes", default={})
    add(macro("QFNonEmpty", integer(qf.get("n_nonempty"))))
    add(macro("QFVerbatim", integer(cls.get("verbatim_in_shown"))))
    add(macro("QFNormalised", integer(cls.get("recovered_by_normalisation"))))
    add(macro("QFElision", integer(cls.get("elision_of_shown"))))
    add(macro("QFReserial", integer(cls.get("reserialised_from_shown"))))
    add(macro("QFElsewhere", integer((cls.get("elsewhere_in_same_paper") or 0)
                                     + (cls.get("reserialised_from_elsewhere") or 0))))
    add(macro("QFAbsent", integer(cls.get("absent_from_source_document"))))
    add(macro("QFEmpty", integer(cls.get("empty"))))
    add(macro("QFSupported", pct(qf.get("share_supported_by_shown_passage"), 1)))
    add(macro("QFAbsentPct", pct(qf.get("share_absent_from_source_document"), 1)))
    add(
        macro(
            "QFOtherPct",
            pct(1 - (qf.get("classes", {}).get("verbatim_in_shown", 0) / (qf.get("n_nonempty") or 1)), 0),
        )
    )

    # ---------------- disclosure counterfactual ------------------------------
    hv = dig(disc, "high_vs_low", default={})
    add(macro("DiscHighK", num(hv.get("kappa_high"))))
    add(macro("DiscLowK", num(hv.get("kappa_low"))))
    add(macro("DiscDiff", signed(hv.get("difference"))))
    add(macro("DiscDiffCI", ci(hv.get("difference_ci95"))))
    add(macro("DiscHighN", integer(hv.get("n_high"))))
    add(macro("DiscLowN", integer(hv.get("n_low"))))

    # ---------------- kappa ceilings (W6, W7) --------------------------------
    for field, short in (("c1", "COne"), ("c2", "CTwo"), ("c3", "CThree"),
                         ("c4", "CFour"), ("c5", "CFive"), ("verdict", "Verdict")):
        blk = dig(prev, "fields", field, default={})
        add(macro(f"Kmax{short}", num(blk.get("max_attainable_kappa"))))
        add(macro(f"KShare{short}", pct(blk.get("kappa_as_share_of_attainable"), 0)))
        add(macro(f"Prev{short}", pct(blk.get("majority_label_share"), 1)))
        add(macro(f"Obs{short}", num(blk.get("observed_agreement"))))
    add(macro("KmaxCensusBin", num(dig(lspace, "census", "binary", "max_attainable_kappa"))))
    add(macro("KCensusBin", num(dig(lspace, "census", "binary", "fleiss_kappa"))))
    add(macro("KInsBin", num(dig(lspace, "constructed_full_disclosure", "binary", "fleiss_kappa"))))
    add(macro("KmaxInsBin", num(dig(lspace, "constructed_full_disclosure", "binary", "max_attainable_kappa"))))
    add(macro("KShareCensus", pct(dig(lspace, "census", "three_class", "kappa_share_of_attainable"), 0)))
    add(macro("KShareIns", pct(dig(lspace, "constructed_full_disclosure", "three_class", "kappa_share_of_attainable"), 0)))
    add(macro("KGapBinary", num(dig(lspace, "gaps", "binary_kappa_gap"))))
    add(macro("KGapThree", num(dig(lspace, "gaps", "three_class_kappa_gap"))))
    add(macro("NarrowsReachN", integer(dig(lspace, "census", "narrows_reachability", "n_items_any_judge_said_narrows"))))

    # ---------------- recall sensitivity (W4) --------------------------------
    add(macro("RecTransMissedN", integer(dig(recall, "n_missed_with_majority_transported"))))
    add(macro("RecTransEligN", integer(dig(recall, "n_missed_transported_and_eligible"))))
    add(macro("RecReimplEligN", integer(dig(recall, "n_missed_reimplemented_and_eligible"))))
    add(macro("RecPerturbAll", pct(dig(recall, "sensitivity", "all_transported_items_reassigned_to_reimplemented"), 1)))
    add(macro("RecPerturbDouble", pct(dig(recall, "sensitivity", "transported_count_doubled"), 1)))
    add(macro("RecPaperCI", ci(dig(recall, "paper_cluster_bootstrap", "ci95"), 3)))

    # ---------------- sampling frame (W3) ------------------------------------
    add(macro("FlowRetrieved", integer(dig(flow, "stages", 0, "output_n"))))
    add(macro("FlowOpenPDF", integer(dig(flow, "stages", 1, "output_n"))))
    add(macro("FlowDedup", integer(dig(flow, "stages", 2, "output_n"))))
    add(macro("FlowScreened", integer(dig(flow, "stages", 3, "output_n"))))
    add(macro("FlowTexts", integer(dig(flow, "screened_corpus", "n_full_texts"))))
    add(macro("FlowQueries", integer(dig(flow, "n_arxiv_queries"))))
    add(macro("FlowSnapshot", dig(flow, "snapshot_date", default=MISSING)))
    years = dig(flow, "screened_corpus", "arxiv_year_distribution", default={})
    if years:
        keys = sorted(years)
        add(macro("FlowYearLo", keys[0]))
        add(macro("FlowYearHi", keys[-1]))

    # ---------------- sigma_r interval (W10) ---------------------------------
    env = dig(sigma, "anchor_envelope_sigma_r", default=[None, None])
    add(macro("SigEnvLo", num(env[0])))
    add(macro("SigEnvHi", num(env[1])))
    add(macro("SigTypeILo", pct(dig(sigma, "source_level_type_I_across_envelope", "min"), 0)))
    add(macro("SigTypeIHi", pct(dig(sigma, "source_level_type_I_across_envelope", "max"), 0)))
    add(macro("SigInsRatio", num(dig(sigma, "anchors", "instrument_benchmark", "ci_width_ratio"), 1)))

    # ---------------- abstention arm (W2/Q4) ---------------------------------
    if absn:
        add(macro("AbsN", integer(dig(absn, "n_items"))))
        add(macro("AbsShare", pct(dig(absn, "abstention_share"), 1)))
        add(macro("AbsK", num(dig(absn, "fleiss_kappa_four_class"))))
        add(macro("AbsKCI", ci(dig(absn, "fleiss_kappa_four_class_ci95"))))
        add(macro("AbsKCollapsed", num(dig(absn, "fleiss_kappa_collapsed_to_deployed_space"))))
        add(macro("AbsKDeployed", num(dig(absn, "fleiss_kappa_deployed_arm"))))
        add(macro("AbsKDiff", signed(dig(absn, "kappa_difference"))))
        add(macro("AbsKDiffCI", ci(dig(absn, "kappa_difference_ci95"))))
        add(macro("AbsKmax", num(dig(absn, "max_attainable_kappa_four_class"))))
        add(macro("AbsSurvivesDrop", signed(dig(absn, "survives_share_change"))))
        add(macro("AbsPerJudgeLo", pct(dig(absn, "abstention_share_min"), 0)))
        add(macro("AbsPerJudgeHi", pct(dig(absn, "abstention_share_max"), 0)))

    # ---------------- open-weight judge pool (W10, generalisation) -----------
    owj = load(SUP / "open_weight_judge_results.json")
    if owj:
        sg = dig(owj, "sigma_r", default={})
        add(macro("OwjNOpen", integer(dig(owj, "n_open_judges"))))
        add(macro("OwjNApi", integer(sg.get("n_judges_api"))))
        add(macro("OwjNTotal", integer(sg.get("n_judges_total"))))
        add(macro("OwjSigApi", num(sg.get("sigma_r_api_only"))))
        add(macro("OwjSigOpen", num(sg.get("sigma_r_open_only"))))
        add(macro("OwjSigPooled", num(sg.get("sigma_r_pooled"))))
        add(macro("OwjSigPooledCI", ci(sg.get("sigma_r_pooled_ci95"))))
        add(macro("OwjSigRatio", num(sg.get("ci_width_ratio_pooled"), 1)))
        cv = dig(owj, "census_verdict", default={})
        add(macro("OwjCensusN", integer(cv.get("n_common_items"))))
        for pool, tag in (("api_pool", "Api"), ("open_pool", "Open"), ("pooled", "All")):
            b = dig(cv, pool, default={})
            add(macro(f"OwjK{tag}", num(b.get("fleiss_kappa"))))
            add(macro(f"OwjKmax{tag}", num(b.get("max_attainable_kappa"))))
            add(macro(f"OwjNJudge{tag}", integer(b.get("n_judges"))))
        grad = dig(owj, "capability_gradient", default={})
        if grad:
            shares = {k: v.get("survives_share") for k, v in grad.items()
                      if v.get("survives_share") is not None}
            if shares:
                add(macro("OwjSurvLo", pct(min(shares.values()), 0)))
                add(macro("OwjSurvHi", pct(max(shares.values()), 0)))
            # the sharpest form: same parameter count, different threshold
            by_size = {}
            for k, v in grad.items():
                if v.get("params_b") is not None and v.get("survives_share") is not None:
                    by_size.setdefault(v["params_b"], []).append((k, v["survives_share"]))
            best = None
            for size, items in by_size.items():
                if len(items) >= 2:
                    lo = min(items, key=lambda x: x[1])
                    hi = max(items, key=lambda x: x[1])
                    spread = hi[1] - lo[1]
                    if best is None or spread > best[0]:
                        best = (spread, size, lo, hi)
            biggest = max(
                (v for v in grad.values() if v.get("params_b")),
                key=lambda v: v["params_b"], default=None)
            if biggest:
                add(macro("OwjBigSize", f"{int(biggest['params_b'])}B"))
                add(macro("OwjBigSurv", pct(biggest["survives_share"], 0)))
            if best:
                add(macro("OwjPairSize", f"{int(best[1])}B"))
                add(macro("OwjPairLoName", best[2][0].replace("_", r"\_")))
                add(macro("OwjPairHiName", best[3][0].replace("_", r"\_")))
                add(macro("OwjPairLo", pct(best[2][1], 0)))
                add(macro("OwjPairHi", pct(best[3][1], 0)))

        ab = dig(owj, "abstention_open", default={})
        add(macro("OwjAbsShare", pct(ab.get("abstention_share"), 1)))
        add(macro("OwjAbsDiff", signed(ab.get("kappa_difference_collapsed_minus_deployed"))))

    # ---------------- evidence map (survey synthesis base) --------------------
    try:
        import csv as _csv

        with (SUP / "evidence_map_venue_expanded_adjudicated.csv").open(
            encoding="utf-8"
        ) as fh:
            rows = list(_csv.DictReader(fh))
        add(macro("MapRows", integer(len(rows))))
        pre = sum(
            1
            for r in rows
            if (r.get("source_or_venue") or "").strip().lower() == "arxiv"
        )
        add(macro("MapPreprints", integer(pre)))
        add(macro("MapPeerReviewed", integer(len(rows) - pre)))
    except Exception:  # noqa: BLE001
        pass

    # ---------------- motivating case (W14) ----------------------------------
    add(macro("MotivChecks", integer(dig(motiv, "n_checks"))))
    add(macro("MotivPassed", integer(dig(motiv, "n_passed"))))

    out = TAB / "revision3_macros.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    missing = sum(1 for l in lines if MISSING in l)
    print(f"wrote {out} with {len(lines) - 1} macros ({missing} unresolved)")
    if missing:
        for l in lines:
            if MISSING in l:
                print("  unresolved:", l)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
