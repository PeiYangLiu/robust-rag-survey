#!/usr/bin/env python3
"""What excluding C3 from the decision rule costs, stated as a number.

The intervention exclusion is a definition, so no measurement falsifies it.
What a reader can still be given is its price: how many census verdicts would
change if C3 mismatch were treated as blocking. This reads the released census
ledger, whose ``majority_c*`` columns are the deployed panel's majority
coordinate labels on the \CensusEligible{} eligible windows.

Writes ``supplement/c3_exclusion_price.json`` and macros prefixed ``Cthree``
into ``tables/revision4_c3_macros.tex``.
"""

from __future__ import annotations

import argparse
import csv
import json
import pathlib
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[2]
SUP = ROOT / "supplement"
GATING = ["c1", "c2", "c4", "c5"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ledger", type=pathlib.Path, default=SUP / "cross_paper_census_ledger.csv")
    parser.add_argument("--out", type=pathlib.Path, default=SUP / "c3_exclusion_price.json")
    parser.add_argument("--macros", type=pathlib.Path, default=ROOT / "tables" / "revision4_c3_macros.tex")
    args = parser.parse_args()

    rows = list(csv.DictReader(args.ledger.open(encoding="utf-8-sig")))

    stated, composed, gated = Counter(), Counter(), Counter()
    changed = 0
    n_composed = 0
    c3_labels = Counter()

    for row in rows:
        stated[(row.get("majority_verdict") or "no_majority").strip().lower()] += 1
        c3 = (row.get("majority_c3") or "").strip().lower()
        c3_labels[c3 or "no_majority"] += 1

        values = [(row.get(f"majority_{c}") or "").strip().lower() for c in GATING]
        if all(values):
            call = "survives" if all(v == "match" for v in values) else "undefined"
            composed[call] += 1
            n_composed += 1
            with_c3 = "undefined" if (c3 and c3 != "match") else call
            gated[with_c3] += 1
            changed += int(with_c3 != call)
        else:
            composed["no_majority"] += 1
            gated["no_majority"] += 1

    surv_without = composed.get("survives", 0)
    surv_with = gated.get("survives", 0)

    results = {
        "n_eligible_items": len(rows),
        "stated_verdict_distribution": dict(stated),
        "composed_without_c3": dict(composed),
        "composed_with_c3_gating": dict(gated),
        "n_items_with_a_composed_verdict": n_composed,
        "n_verdicts_changed_by_adding_c3": changed,
        "share_changed": changed / n_composed if n_composed else float("nan"),
        "survives_without_c3": surv_without,
        "survives_with_c3": surv_with,
        "share_of_survives_destroyed": (
            (surv_without - surv_with) / surv_without if surv_without else float("nan")
        ),
        "c3_majority_label_counts": dict(c3_labels),
        "note": (
            "Adding C3 to the rule is not a hypothesis this data can reject or "
            "confirm; it is a design choice whose consequence is reported here so "
            "a reader who disagrees can see what disagreeing would cost."
        ),
    }
    args.out.write_text(json.dumps(results, indent=2), encoding="utf-8")

    lines = [
        "% Generated by scripts/revision4/analyze_c3_exclusion_price.py -- do not edit by hand.",
        f"\\newcommand{{\\CthreeGateChanged}}{{{changed}}}",
        f"\\newcommand{{\\CthreeGateN}}{{{n_composed}}}",
        f"\\newcommand{{\\CthreeGateShare}}{{{100 * results['share_changed']:.0f}}}",
        f"\\newcommand{{\\CthreeSurvWithout}}{{{surv_without}}}",
        f"\\newcommand{{\\CthreeSurvWith}}{{{surv_with}}}",
        f"\\newcommand{{\\CthreeSurvKilled}}{{{100 * results['share_of_survives_destroyed']:.0f}}}",
        f"\\newcommand{{\\CthreeMismatchCount}}{{{c3_labels.get('mismatch', 0)}}}",
    ]
    args.macros.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(results, indent=2))
    print(f"\nwrote {args.out}\nwrote {args.macros}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
