#!/usr/bin/env python3
"""Surface per-judge instrument-quality diagnostics as body-level macros.

A paper whose thesis is that unverified declarations are not evidence has to
print its own instrument's infidelity and quote-fabrication rates in the body,
not only in a generated appendix table. This lifts them out of
``supplement/census_diagnostics.json`` into macros prefixed ``Rule`` and ``QF``.
"""

from __future__ import annotations

import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--diagnostics", type=pathlib.Path, default=ROOT / "supplement" / "census_diagnostics.json"
    )
    parser.add_argument(
        "--macros", type=pathlib.Path, default=ROOT / "tables" / "revision4_diag_macros.tex"
    )
    args = parser.parse_args()

    data = json.loads(args.diagnostics.read_text(encoding="utf-8"))
    fidelity = data["composed_rule"]["per_judge_rule_fidelity"]
    quotes = data["quote_forensics"]

    ranked = sorted(fidelity.items(), key=lambda kv: kv[1]["rate"])
    worst_name, worst = ranked[0]
    best_name, best = ranked[-1]

    lines = [
        "% Generated by scripts/revision4/build_diagnostic_macros.py -- do not edit by hand.",
        f"\\newcommand{{\\RuleFidelityLo}}{{{worst['rate']:.2f}}}",
        f"\\newcommand{{\\RuleFidelityHi}}{{{best['rate']:.2f}}}",
        f"\\newcommand{{\\RuleContraWorst}}{{{worst['survives_contradicted']}}}",
        f"\\newcommand{{\\RuleContraWorstN}}{{{worst['n']}}}",
        f"\\newcommand{{\\RuleContraWorstPct}}{{{100 * (1 - worst['rate']):.0f}}}",
        f"\\newcommand{{\\RuleContraTotal}}{{{sum(v['survives_contradicted'] for v in fidelity.values())}}}",
        f"\\newcommand{{\\RuleJudgesClean}}{{{sum(1 for v in fidelity.values() if v['survives_contradicted'] == 0)}}}",
        f"\\newcommand{{\\QFChecked}}{{{quotes['n_codings_checked']:,}}}",
        f"\\newcommand{{\\QFVerbatimPct}}{{{100 * quotes['classes']['verbatim_in_shown'] / quotes['n_nonempty']:.0f}}}",
    ]

    prevalence_path = args.diagnostics.parent / "coordinate_prevalence.json"
    if prevalence_path.exists():
        fields = json.loads(prevalence_path.read_text(encoding="utf-8"))["fields"]
        silence = {}
        for coord in ["c1", "c2", "c3", "c4", "c5"]:
            counts = fields[coord]["label_counts"]
            total = sum(counts.values())
            silence[coord] = 100 * counts.get("not_determinable", 0) / total
        quietest = max(silence, key=silence.get)
        loudest = min(silence, key=silence.get)
        lines += [
            f"\\newcommand{{\\SilentCoord}}{{{quietest.upper()}}}",
            f"\\newcommand{{\\SilentPct}}{{{silence[quietest]:.0f}}}",
            f"\\newcommand{{\\SilentNextPct}}{{{sorted(silence.values())[-2]:.0f}}}",
            f"\\newcommand{{\\SilentLoudCoord}}{{{loudest.upper()}}}",
            f"\\newcommand{{\\SilentLoudPct}}{{{silence[loudest]:.0f}}}",
        ]
    args.macros.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {args.macros}  (worst judge: {worst_name}, best: {best_name})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
