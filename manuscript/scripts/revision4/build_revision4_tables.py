#!/usr/bin/env python3
"""Emit the two revision-4 LaTeX tables from the analysis artifacts.

Writes ``tables/provenance_gate_sensitivity.tex`` (reviewer Q7) and
``tables/privileged_reference_bounds.tex`` (reviewer Q6) in the booktabs house
style used elsewhere in ``tables/``.  Reads only the JSON the revision4 analysis
scripts produce; changes no upstream artifact.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SUP = REPO / "manuscript" / "supplement"
TAB = REPO / "manuscript" / "tables"


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def f2(x, nd=2):
    return f"{float(x):.{nd}f}"


def f3(x):
    return f"{float(x):.3f}"


def pval_math(p):
    p = float(p)
    if p < 0.001:
        return "{<}0.001"
    if p < 0.01:
        return f"{{=}}{p:.3f}"
    return f"{{=}}{p:.2f}"


def ci_txt(pair, nd=2):
    return f"[{float(pair[0]):.{nd}f}, {float(pair[1]):.{nd}f}]"


# ---------------------------------------------------------------- Table 1: gate
def build_gate_table(gate: dict) -> str:
    g = gate["gates"]
    loo = gate["leave_one_out_majority_gate"]

    def row(label, blk):
        return (f"{label} & {blk['n_classified']} & {blk['n_reimplemented']} & "
                f"{blk['n_transported']} & {blk['n_unclear']} & "
                f"{f3(blk['reimplemented_share'])} & {ci_txt(blk['wilson_ci95'])} \\\\")

    short = {"coderA_gpt5mini": "coder\\,A (gpt5mini)",
             "coderB_claudeopus46": "coder\\,B (opus46)",
             "coderC_gemini31pro": "coder\\,C (gemini31pro)"}
    loo_rows = []
    for cfg in loo["configs"]:
        loo_rows.append(
            f"\\quad drop {short[cfg['dropped_judge']]} & {cfg['n_classified']} & "
            f"{cfg['n_reimplemented']} & {cfg['n_transported']} & {cfg['n_unclear']} & "
            f"{f3(cfg['reimplemented_share'])} & {ci_txt(cfg['wilson_ci95'])} \\\\")

    lines = [
        "% Generated by scripts/revision4/build_revision4_tables.py -- do not edit.",
        "\\begin{table}[t]",
        "\\centering\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lrrrrrr@{}}",
        "\\toprule",
        "Eligibility gate & Class. & Re-impl. & Transp. & Unclear & Share & 95\\% CI \\\\",
        "\\midrule",
        row("Unanimous ($3/3$)", g["a_unanimous"]),
        row("Majority ($\\geq\\!2/3$)", g["b_majority"]),
        row("Any judge ($\\geq\\!1/3$)$^{\\dagger}$", g["c_any_judge"]),
        row("No gate$^{\\dagger}$", g["d_no_gate"]),
        "\\midrule",
        "\\multicolumn{7}{@{}l}{\\emph{Majority gate, leave one coder out}} \\\\",
        *loo_rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Reviewer Q7: the re-implementation share is stable under the "
        "eligibility gate. \\emph{Class.}\\ is the number of windows the "
        "provenance panel assigned to re-implemented or transported (its "
        "denominator); \\emph{Share} is re-implemented over that count with a "
        "Wilson interval. The majority row reproduces the published "
        f"{g['b_majority']['n_reimplemented']}/{g['b_majority']['n_classified']} "
        f"$=\\,{f3(g['b_majority']['reimplemented_share'])}$ exactly. Tightening the "
        "gate to unanimous or dropping any one coder moves the share by at most "
        "$0.02$ (leave-one-out range "
        f"{f3(loo['share_min'])}--{f3(loo['share_max'])}). $^{{\\dagger}}$The "
        "provenance pass was elicited only on the majority-eligible ledger, so "
        "no window that fails the majority gate carries a provenance label: the "
        "any-judge row necessarily equals the majority row over coded windows "
        f"({g['c_any_judge']['n_missing_provenance']} of the "
        f"{g['c_any_judge']['n_gate_eligible']} any-judge-eligible windows have "
        "no label and are not invented), and the no-gate row adds only the "
        f"{g['d_no_gate']['n_absent_from_current_frame']} coded windows now "
        "outside the frame.}",
        "\\label{tab:provenance-gate-sensitivity}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


# ------------------------------------------------------------- Table 2: bounds
def build_bounds_table(b: dict) -> str:
    vd, pv = b["verdict"], b["provenance"]
    con = b["characterization_no_majority_vs_established"]["continuous"]
    cat = b["characterization_no_majority_vs_established"]["categorical"]

    def bd_rows(prefix_label, blk):
        bd = blk["by_denominator"]
        return [
            f"{prefix_label}: scored ({blk['n_correct']}/{blk['n_scored']}) & "
            f"{blk['n_scored']} & {f2(blk['accuracy'])} & {f2(blk['accuracy'])} \\\\",
            f"\\quad over full sample & {bd['full_sample']['denominator']} & "
            f"{f2(bd['full_sample']['worst_case_accuracy'])} & "
            f"{f2(bd['full_sample']['best_case_accuracy'])} \\\\",
            f"\\quad over deployed-committed & {bd['deployed_committed']['denominator']} & "
            f"{f2(bd['deployed_committed']['worst_case_accuracy'])} & "
            f"{f2(bd['deployed_committed']['best_case_accuracy'])} \\\\",
        ]

    # characterisation rows: Feature | Estab. | No-maj. | Test (p, effect)
    st = cat["stratum"]
    sidx = st["levels"].index("survey_table")
    dm = cat["deployed_reached_majority"]
    ev = con["reference_vote_entropy_raw"]
    nv = con["n_verified_reference_votes"]
    wl = con["window_length_words"]
    cd = con["coordinate_terms_mentioned"]

    def cont_row(label, e, use_mean, tail):
        key = "mean" if use_mean else "median"
        nd = 2 if use_mean else 0
        return (f"{label} & {f2(e['established'][key], nd)} & {f2(e['no_majority'][key], nd)} & "
                f"$p{pval_math(e['p_value'])}$, $\\delta{{=}}{e['cliffs_delta']:+.2f}$ {tail}\\\\")

    char_rows = [
        cont_row("Quote-verified ref.\\ votes (med.)", nv, False, ""),
        cont_row("Ref.\\ vote-split entropy (mean)", ev, True, ""),
        (f"Survey-table stratum (share) & {f2(st['established_counts'][sidx]/sum(st['established_counts']))} & "
         f"{f2(st['no_majority_counts'][sidx]/sum(st['no_majority_counts']))} & "
         f"$p{pval_math(st['p_value'])}$, $V{{=}}{f2(st['cramers_v'])}$ \\\\"),
        (f"Deployed panel commits (rate) & {f2(dm['established_commit_rate'])} & "
         f"{f2(dm['no_majority_commit_rate'])} & "
         f"$p{pval_math(dm['fisher_p_value'])}$, $V{{\\approx}}0$ \\\\"),
        cont_row("Window length (med.\\ words)", wl, False, ""),
        cont_row("Coordinate terms (median)", cd, False, ""),
    ]

    lines = [
        "% Generated by scripts/revision4/build_revision4_tables.py -- do not edit.",
        "\\begin{table}[t]",
        "\\centering\\scriptsize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lrrr@{}}",
        "\\toprule",
        "\\multicolumn{4}{@{}l}{\\emph{Worst-/best-case accuracy folding in excluded windows}} \\\\",
        "Setting & $N$ & Worst & Best \\\\",
        "\\midrule",
        *bd_rows("Verdict", vd),
        f"\\quad reviewer $114{{+}}51$ & {vd['by_denominator']['reviewer_scored_plus_all_no_majority']['denominator']} & "
        f"{f2(vd['by_denominator']['reviewer_scored_plus_all_no_majority']['worst_case_accuracy'])} & "
        f"{f2(vd['by_denominator']['reviewer_scored_plus_all_no_majority']['best_case_accuracy'])} \\\\",
        *bd_rows("Provenance", pv),
        "\\midrule",
        "\\multicolumn{4}{@{}l}{\\emph{No-majority ("
        f"{b['characterization_no_majority_vs_established']['groups']['no_majority']}) vs.\\ "
        f"established ({b['characterization_no_majority_vs_established']['groups']['established']}) "
        "verdict windows}} \\\\",
        "Feature & Estab. & No-maj. & Test \\\\",
        "\\midrule",
        *char_rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Reviewer Q6: bounds and characterisation for the excluded "
        "privileged-reference windows. \\emph{Top:} the deployed panel is scored "
        f"only where the reference reached a quote-verified majority (verdict "
        f"{vd['n_correct']}/{vd['n_scored']}$=\\,${f2(vd['accuracy'])}, Wilson "
        f"{ci_txt(vd['wilson_ci95'])}; provenance {pv['n_correct']}/{pv['n_scored']}"
        f"$=\\,${f2(pv['accuracy'])}, {ci_txt(pv['wilson_ci95'])}). Worst case counts "
        "the panel wrong on every folded-in window, best case right. The "
        "reviewer's $114{+}51{=}165$ denominator overstates the panel's "
        "committed set: only "
        f"{vd['accounting']['crosstab']['ref_no_maj_and_deployed_committed']} of the "
        f"{vd['accounting']['n_reference_no_majority']} no-reference-majority "
        f"windows carry a deployed verdict, so the deployed-committed total is "
        f"{vd['accounting']['n_deployed_committed']}, not 165. \\emph{{Bottom:}} the "
        "no-majority windows differ from the rest mainly in having fewer "
        "quote-verified privileged votes and more split ones, and in stratum "
        "mix; they are not longer, denser in coordinate terms, or harder for the "
        "deployed panel, which commits on them at the same rate. Continuous "
        "features: Mann--Whitney $p$ and Cliff's $\\delta$; categorical: "
        "$\\chi^2$ $p$ and Cram\\'er's $V$ (deployed-commits uses Fisher).}",
        "\\label{tab:privileged-reference-bounds}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    gate = load(SUP / "provenance_gate_sensitivity.json")
    bounds = load(SUP / "privileged_reference_bounds.json")
    (TAB / "provenance_gate_sensitivity.tex").write_text(build_gate_table(gate), encoding="utf-8")
    (TAB / "privileged_reference_bounds.tex").write_text(build_bounds_table(bounds), encoding="utf-8")
    print(f"wrote {TAB / 'provenance_gate_sensitivity.tex'}")
    print(f"wrote {TAB / 'privileged_reference_bounds.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
