#!/usr/bin/env python3
"""Emit LaTeX macros for the revision-4 reviewer answers (Q6 bounds, Q7 gate).

Reads the two artifacts produced by the revision4 analysis scripts and writes
``tables/revision4_macros.tex``.  Every headline number the manuscript prints
about the gate-sensitivity check or the privileged-reference bounds is emitted
here so prose and tables stay in lockstep with the artifact.  Gate macros are
prefixed ``\\Gate``; bound and characterisation macros are prefixed ``\\Bound``.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SUP = REPO / "manuscript" / "supplement"
TAB = REPO / "manuscript" / "tables"
MISSING = r"\textbf{??}"


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def num(x, nd=2):
    if x is None or (isinstance(x, float) and x != x):
        return MISSING
    return f"{float(x):.{nd}f}"


def pct(x, nd=0):
    if x is None or (isinstance(x, float) and x != x):
        return MISSING
    return f"{float(x) * 100:.{nd}f}"


def integer(x):
    if x is None:
        return MISSING
    return f"{int(x):,}"


def ci(pair, nd=2):
    if not pair or len(pair) != 2 or any(p is None or p != p for p in pair):
        return MISSING
    return f"[{float(pair[0]):.{nd}f}, {float(pair[1]):.{nd}f}]"


def signed(x, nd=2):
    if x is None or (isinstance(x, float) and x != x):
        return MISSING
    return f"{float(x):+.{nd}f}"


def pval(p):
    if p is None or (isinstance(p, float) and p != p):
        return MISSING
    p = float(p)
    if p < 0.001:
        return r"\ensuremath{<}0.001"  # mode-safe '<' for text or math contexts
    if p < 0.01:
        return f"{p:.3f}"
    return f"{p:.2f}"


def main() -> int:
    gate = load(SUP / "provenance_gate_sensitivity.json")
    bounds = load(SUP / "privileged_reference_bounds.json")
    lines = [
        "% Generated by scripts/revision4/build_revision4_macros.py -- do not edit by hand."
    ]

    # ---- Task 1: gate sensitivity (\Gate*) ---------------------------------
    fr = gate["frame"]
    lines += [
        macro("GateNUnanimousElig", integer(fr["n_unanimous_eligible"])),
        macro("GateNMajorityElig", integer(fr["n_majority_eligible"])),
        macro("GateNAnyElig", integer(fr["n_any_judge_eligible"])),
        macro("GateNProvCoded", integer(gate["provenance"]["n_coded_by_all_provenance_judges"])),
    ]
    g = gate["gates"]

    def gate_macros(prefix: str, blk: dict):
        return [
            macro(f"Gate{prefix}N", integer(blk["n_classified"])),
            macro(f"Gate{prefix}Reimp", integer(blk["n_reimplemented"])),
            macro(f"Gate{prefix}Trans", integer(blk["n_transported"])),
            macro(f"Gate{prefix}Unclear", integer(blk["n_unclear"])),
            macro(f"Gate{prefix}Share", num(blk["reimplemented_share"], 3)),
            macro(f"Gate{prefix}SharePct", pct(blk["reimplemented_share"], 1)),
            macro(f"Gate{prefix}CI", ci(blk["wilson_ci95"], 2)),
        ]

    lines += gate_macros("Unan", g["a_unanimous"])
    lines += gate_macros("Maj", g["b_majority"])
    lines += gate_macros("Any", g["c_any_judge"])
    lines += gate_macros("NoGate", g["d_no_gate"])
    lines += [
        macro("GateAnyGateEligible", integer(g["c_any_judge"]["n_gate_eligible"])),
        macro("GateAnyMissingProv", integer(g["c_any_judge"]["n_missing_provenance"])),
        macro("GateNoGateAbsentFrame", integer(g["d_no_gate"]["n_absent_from_current_frame"])),
    ]
    loo = gate["leave_one_out_majority_gate"]
    lines += [
        macro("GateLooShareMin", num(loo["share_min"], 3)),
        macro("GateLooShareMax", num(loo["share_max"], 3)),
        macro("GateLooRange", f"{num(loo['share_min'], 3)}--{num(loo['share_max'], 3)}"),
        macro(
            "GateLooRangePct",
            f"{100 * loo['share_min']:.1f}--{100 * loo['share_max']:.1f}",
        ),
    ]
    short = {"coderA_gpt5mini": "DropA", "coderB_claudeopus46": "DropB", "coderC_gemini31pro": "DropC"}
    for cfg in loo["configs"]:
        tag = short[cfg["dropped_judge"]]
        lines += [
            macro(f"GateLoo{tag}N", integer(cfg["n_classified"])),
            macro(f"GateLoo{tag}Share", num(cfg["reimplemented_share"], 3)),
            macro(f"GateLoo{tag}CI", ci(cfg["wilson_ci95"], 2)),
        ]

    # ---- Task 2: privileged-reference bounds (\Bound*) ---------------------
    lines.append("% -- privileged-reference bounds (reviewer Q6)")
    lines.append(macro("BoundSampleN", integer(bounds["sample"]["n_windows"])))
    lines.append(macro("BoundSamplePapers", integer(bounds["sample"]["n_papers"])))

    def bound_macros(prefix: str, blk: dict):
        ac = blk["accounting"]
        ct = ac["crosstab"]
        bd = blk["by_denominator"]
        out = [
            macro(f"Bound{prefix}BaseN", integer(blk["n_scored"])),
            macro(f"Bound{prefix}BaseCorrect", integer(blk["n_correct"])),
            macro(f"Bound{prefix}BaseAcc", num(blk["accuracy"], 2)),
            macro(f"Bound{prefix}BaseWilson", ci(blk["wilson_ci95"], 2)),
            macro(f"Bound{prefix}RefMaj", integer(ac["n_reference_majority"])),
            macro(f"Bound{prefix}RefNoMaj", integer(ac["n_reference_no_majority"])),
            macro(f"Bound{prefix}DepCommit", integer(ac["n_deployed_committed"])),
            macro(f"Bound{prefix}DepAbstain", integer(ac["n_deployed_abstained"])),
            macro(f"Bound{prefix}YY", integer(ct["ref_maj_and_deployed_committed"])),
            macro(f"Bound{prefix}YN", integer(ct["ref_maj_and_deployed_abstained"])),
            macro(f"Bound{prefix}NY", integer(ct["ref_no_maj_and_deployed_committed"])),
            macro(f"Bound{prefix}NN", integer(ct["ref_no_maj_and_deployed_abstained"])),
            macro(f"Bound{prefix}FullN", integer(bd["full_sample"]["denominator"])),
            macro(f"Bound{prefix}FullWorst", num(bd["full_sample"]["worst_case_accuracy"], 2)),
            macro(f"Bound{prefix}FullBest", num(bd["full_sample"]["best_case_accuracy"], 2)),
            macro(f"Bound{prefix}CommitN", integer(bd["deployed_committed"]["denominator"])),
            macro(f"Bound{prefix}CommitWorst", num(bd["deployed_committed"]["worst_case_accuracy"], 2)),
            macro(f"Bound{prefix}CommitBest", num(bd["deployed_committed"]["best_case_accuracy"], 2)),
        ]
        rev = bd["reviewer_scored_plus_all_no_majority"]
        out += [
            macro(f"Bound{prefix}ReviewerN", integer(rev["denominator"])),
            macro(f"Bound{prefix}ReviewerWorst", num(rev["worst_case_accuracy"], 2)),
            macro(f"Bound{prefix}ReviewerBest", num(rev["best_case_accuracy"], 2)),
        ]
        return out

    lines += bound_macros("Vd", bounds["verdict"])
    lines += bound_macros("Pv", bounds["provenance"])
    # the exact accounting correction the reviewer's 165 needs
    vct = bounds["verdict"]["accounting"]["crosstab"]
    lines.append(macro("BoundVdReviewerCommitted",
                       f"{vct['ref_no_maj_and_deployed_committed']} of {bounds['verdict']['accounting']['n_reference_no_majority']}"))

    # ---- characterisation of the 51 vs 129 ---------------------------------
    char = bounds["characterization_no_majority_vs_established"]
    con = char["continuous"]
    cat = char["categorical"]
    lines.append("% -- characterisation of the reference-no-majority verdict windows")
    lines += [
        macro("BoundCharEstab", integer(char["groups"]["established"])),
        macro("BoundCharNoMaj", integer(char["groups"]["no_majority"])),
    ]

    def cont_macros(prefix: str, field: str, use_mean: bool):
        e = con[field]
        key = "mean" if use_mean else "median"
        nd = 2 if use_mean else 0
        return [
            macro(f"BoundChar{prefix}Est", num(e["established"][key], nd)),
            macro(f"BoundChar{prefix}NoMaj", num(e["no_majority"][key], nd)),
            macro(f"BoundChar{prefix}P", pval(e["p_value"])),
            macro(f"BoundChar{prefix}Delta", signed(e["cliffs_delta"], 2)),
        ]

    lines += cont_macros("VerifVotes", "n_verified_reference_votes", use_mean=False)
    lines += cont_macros("Entropy", "reference_vote_entropy_raw", use_mean=True)
    lines += cont_macros("Wlen", "window_length_words", use_mean=False)
    lines += cont_macros("Coord", "coordinate_terms_mentioned", use_mean=False)

    # deployed commit rate (no difference)
    dm = cat["deployed_reached_majority"]
    lines += [
        macro("BoundCharCommitEst", num(dm["established_commit_rate"], 2)),
        macro("BoundCharCommitNoMaj", num(dm["no_majority_commit_rate"], 2)),
        macro("BoundCharCommitP", pval(dm["fisher_p_value"])),
    ]
    # stratum: survey_table share (survey_table is a level)
    st = cat["stratum"]
    idx = st["levels"].index("survey_table")
    est_total = sum(st["established_counts"])
    nom_total = sum(st["no_majority_counts"])
    lines += [
        macro("BoundCharSurveyEst", num(st["established_counts"][idx] / est_total, 2)),
        macro("BoundCharSurveyNoMaj", num(st["no_majority_counts"][idx] / nom_total, 2)),
        macro("BoundCharSurveyP", pval(st["p_value"])),
        macro("BoundCharSurveyV", num(st["cramers_v"], 2)),
    ]

    out = "\n".join(lines) + "\n"
    (TAB / "revision4_macros.tex").write_text(out, encoding="utf-8")
    print(f"wrote {TAB / 'revision4_macros.tex'} ({len(lines) - 1} macros)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
